package StringMethods;

public class isEmptyString {

	public static void main(String[] args) {
		
		
		String S1 = "" ;
		
		String A = " " ;
		
		String D8 = "Pranav" ;
		
		
		System.out.println(S1.isEmpty());    // true
		System.out.println(A.isEmpty());  // false
		System.out.println(D8.isEmpty());    //false

	}

}
