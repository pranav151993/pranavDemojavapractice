package StringMethods;

public class ValueOfString {

	public static void main(String[] args) {
		
		int a = 23;
		
		String s1 = String.valueOf(a);   //used to convert any non String variable or Object such as int, double, char, and others to a newly created String object. 
		
		System.out.println(20 + s1 );    //2023
		

	}

}
